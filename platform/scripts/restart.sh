#!/usr/bin/env bash
# Перезапуск: остановить и поднять заново. Именно это нужно после обновления кода
# или после правки настроек, которые читаются один раз при старте.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

"$ROOT/scripts/stop.sh"

# Пауза, чтобы система успела освободить порт: сокет после закрытия ещё
# пару мгновений висит в TIME_WAIT, и новый запуск об это спотыкается.
sleep 1

exec "$ROOT/scripts/start.sh"
