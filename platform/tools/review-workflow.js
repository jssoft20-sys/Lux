const found = await parallel(AREAS.map(a => () =>
  agent(a.prompt, { label: a.label, phase: 'Поиск', schema: FINDINGS })))

const all = found.filter(Boolean).flatMap(r => (r.findings || []))
log(`Находок до проверки: ${all.length}`)

phase('Проверка')

const checked = await parallel(all.map(f => () =>
  agent(`${BASE}

Проверь заявленную проблему. Твоя задача — ОПРОВЕРГНУТЬ её, а не подтвердить.
Открой файл, прочитай код вокруг и реши честно.

Файл: ${f.file}${f.line ? ':' + f.line : ''}
Заявлено: ${f.title}
Обоснование автора: ${f.why}

Проблема настоящая только если ты своими глазами увидел в коде путь, который к ней
приводит. Если защита есть выше по стеку, если случай невозможен из-за проверки
в другом месте, если автор неверно прочитал код — ставь real=false и объясни.
Сомневаешься — ставь real=false.`,
    { label: `проверка: ${f.title.slice(0, 40)}`, phase: 'Проверка', schema: VERDICT })
    .then(v => ({ ...f, verdict: v }))))

const confirmed = checked.filter(Boolean).filter(f => f.verdict && f.verdict.real)
const rejected = checked.filter(Boolean).filter(f => !f.verdict || !f.verdict.real)

log(`Подтверждено: ${confirmed.length}, отклонено при проверке: ${rejected.length}`)

const order = { 'критично': 0, 'важно': 1, 'мелочь': 2 }
confirmed.sort((a, b) => (order[a.severity] ?? 3) - (order[b.severity] ?? 3))

return {
  подтверждено: confirmed.length,
  отклонено: rejected.length,
  находки: confirmed.map(f => ({
    важность: f.severity, файл: f.file, строка: f.line || null,
    что: f.title, почему: f.why, как_чинить: f.fix,
    проверка: f.verdict.reason,
  })),
}
